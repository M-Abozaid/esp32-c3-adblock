#!/usr/bin/env python3
"""Parametric enclosure for an ESP8266 dev board (NodeMCU / D1 mini class).

Builds the case from axis-aligned boxes, so no CAD tool is required; every
slicer unions the result correctly.  Measure your board first (width across the
two header rows, length from the USB end to the antenna end), then run:

    python3 esp8266-enclosure.py --board-w 30 --board-l 58 --out case.stl

The case is a tray: the board drops in from the top, the side ribs hold the
header strips, the end wall leaves a hole for the USB plug, and the antenna end
is left open so no plastic sits next to the radio.
"""

import argparse
import struct

PRESETS = {
    "nodemcu30": (30.0, 58.0),
    "nodemcu25": (25.4, 58.0),
    "d1mini": (21.0, 26.5),
}

PCB_T = 1.6
WALL = 2.0
FLOOR_T = 2.0
SIDE_CLEAR = 1.0
WALL_H = 18.0
ANTENNA_OPEN = 13.0
RAIL_H = 2.0
RAIL_W = 3.0
RAIL_INSET = 2.0
RIB_H = 3.0
RIB_INTERFERENCE = 0.2
USB_CUT_W = 16.0
USB_SLOT_H = 9.0
VENT_COUNT = 4
VENT_W = 2.0
VENT_H = 6.0
VENT_Z = 9.0
VENT_START = 8.0
VENT_PITCH = 6.0

BOXES = []


def box(x0, x1, y0, y1, z0, z1):
    BOXES.append((x0, x1, y0, y1, z0, z1))


def build(board_w, board_l):
    del BOXES[:]
    half = board_w / 2.0
    in_half = half + SIDE_CLEAR
    out_half = in_half + WALL
    wall_top = WALL_H
    rail_top = FLOOR_T + RAIL_H
    pcb_top = rail_top + PCB_T
    rib_bottom = pcb_top
    rib_top = rib_bottom + RIB_H
    side_end = board_l - ANTENNA_OPEN

    box(-out_half, out_half, -WALL, board_l, 0.0, FLOOR_T)

    for s in (-1, 1):
        x_out = s * out_half
        x_in = s * in_half
        lo, hi = min(x_out, x_in), max(x_out, x_in)

        box(lo, hi, -WALL, side_end, FLOOR_T, VENT_Z)

        cuts = []
        for i in range(VENT_COUNT):
            v0 = VENT_START + i * VENT_PITCH
            cuts.append((v0, v0 + VENT_W))
        cursor = -WALL
        for v0, v1 in cuts:
            if v0 > cursor:
                box(lo, hi, cursor, v0, VENT_Z, VENT_Z + VENT_H)
            cursor = v1
        box(lo, hi, cursor, side_end, VENT_Z, VENT_Z + VENT_H)
        box(lo, hi, -WALL, side_end, VENT_Z + VENT_H, wall_top)

        rail_out = s * (half - RAIL_INSET)
        rail_in = s * (half - RAIL_INSET - RAIL_W)
        box(min(rail_out, rail_in), max(rail_out, rail_in), 0.0, board_l,
            FLOOR_T, rail_top)

        rib_out = x_in
        rib_in = s * (in_half - SIDE_CLEAR - RIB_INTERFERENCE)
        box(min(rib_out, rib_in), max(rib_out, rib_in), 0.0, side_end,
            rib_bottom, rib_bottom + RIB_H * 0.45)
        rib_in2 = s * (in_half - SIDE_CLEAR - RIB_INTERFERENCE + 0.6)
        box(min(rib_out, rib_in2), max(rib_out, rib_in2), 0.0, side_end,
            rib_bottom + RIB_H * 0.45, rib_top)

    half_cut = USB_CUT_W / 2.0
    slot_top = FLOOR_T + USB_SLOT_H
    box(-in_half, -half_cut, -WALL, 0.0, FLOOR_T, wall_top)
    box(half_cut, in_half, -WALL, 0.0, FLOOR_T, wall_top)
    box(-half_cut, half_cut, -WALL, 0.0, slot_top, wall_top)


FACES = (
    (0, 2, 1), (0, 3, 2),
    (4, 5, 6), (4, 6, 7),
    (0, 1, 5), (0, 5, 4),
    (1, 2, 6), (1, 6, 5),
    (2, 3, 7), (2, 7, 6),
    (3, 0, 4), (3, 4, 7),
)


def box_triangles(b):
    x0, x1, y0, y1, z0, z1 = b
    v = (
        (x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
        (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1),
    )
    for idxs in FACES:
        a, c, d = (v[i] for i in idxs)
        ux, uy, uz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
        vx, vy, vz = d[0] - a[0], d[1] - a[1], d[2] - a[2]
        nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        yield (nx, ny, nz), a, c, d


def write_stl(path, boxes):
    tris = []
    for b in boxes:
        tris.extend(box_triangles(b))
    with open(path, "wb") as f:
        f.write(b"generated by esp8266-enclosure.py".ljust(80, b"\0"))
        f.write(struct.pack("<I", len(tris)))
        for n, a, c, d in tris:
            f.write(struct.pack("<3f", *n))
            f.write(struct.pack("<3f", *a))
            f.write(struct.pack("<3f", *c))
            f.write(struct.pack("<3f", *d))
            f.write(b"\0\0")
    return len(tris)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preset", choices=sorted(PRESETS), default="nodemcu30")
    ap.add_argument("--board-w", type=float)
    ap.add_argument("--board-l", type=float)
    ap.add_argument("--out", default="esp8266-enclosure.stl")
    args = ap.parse_args()

    w, l = PRESETS[args.preset]
    if args.board_w:
        w = args.board_w
    if args.board_l:
        l = args.board_l

    build(w, l)
    n = write_stl(args.out, BOXES)
    out_w = w + 2 * (SIDE_CLEAR + WALL)
    print(f"board {w} x {l} mm -> {args.out}: {n} triangles, "
          f"outer {out_w:.1f} x {l + WALL:.1f} x {WALL_H:.1f} mm")


if __name__ == "__main__":
    main()
